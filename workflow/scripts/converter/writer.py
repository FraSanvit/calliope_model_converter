"""Write a `ConvertedModel` to disk."""

from __future__ import annotations

import io
import math
import shutil
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from converter.builder import ConvertedModel
from converter.diagnostics import Diagnostics
from converter.timeseries import copy_csv, write_derived

HEADER = "# Converted from a Calliope v0.6 model by calliope_model_converter. Legacy source: {source}\n"


def _represent_list(representer, data: list):
    # Lists stay inline (`carrier_out: [electricity, heat]`) unless they hold mappings (e.g. `equations`).
    flow = not any(isinstance(item, dict) for item in data)
    return representer.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


def _yaml() -> YAML:
    yaml = YAML(typ="safe", pure=True)
    yaml.default_flow_style = False  # mappings in block style, as in the Calliope docs
    yaml.sort_base_mapping_type_on_output = False  # keep insertion order (data table order matters)
    yaml.width = 4096
    yaml.allow_unicode = True
    yaml.representer.add_representer(list, _represent_list)  # after the options: this creates the representer
    return yaml


def _plain(value: Any) -> Any:
    """Convert to plain YAML-friendly python types."""
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, list | tuple):
        return [_plain(v) for v in value]
    if isinstance(value, float) and value.is_integer() and not math.isinf(value):
        return value
    if hasattr(value, "item"):  # numpy scalars
        return value.item()
    return value


def dump_yaml(content: dict, path: Path, header: str = "", *, space_entries: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        if header:
            f.write(header)
        stream = io.StringIO()
        _yaml().dump(_plain(content), stream)
        f.write(_space(stream.getvalue(), space_entries))


def _space(text: str, entries: bool) -> str:
    """Blank line before each top-level key except the first.

    With `entries` (math files), also between the entries of each section (each constraint, lookup, ...).
    """
    lines = text.splitlines(keepends=True)
    out = []
    for i, line in enumerate(lines):
        prev = lines[i - 1] if i else ""
        top = line[:1] not in ("", " ", "-", "#", "\n")
        entry = entries and line.startswith("  ") and line[2:3] not in (" ", "-", "#") and prev.startswith("  ")
        if i and (top or entry) and prev.strip():
            out.append("\n")
        out.append(line)
    return "".join(out)


def write_model(model: ConvertedModel, out_dir: Path, diag: Diagnostics, *, copy_csvs: bool = True) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for rel, content in model.yaml_files.items():
        dump_yaml(content, out_dir / rel, HEADER.format(source=rel))
    for rel, content in model.math_files.items():
        dest = out_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, Path):
            shutil.copyfile(content, dest)
        else:
            source = {
                "conversion_plus": "conversion_plus techs",
                "time_varying_limits": "run.py time-varying limits",
                "fuel_distribution": "run.py fuel distribution",
                "storage_ev": "run.py storage_ev_constraint",
                "flow_out_per_month": "run.py carrier_prod_per_month constraints",
                "resample": "time resampling (v0.6 averages timeseries)",
            }.get(dest.stem, "group constraints")
            header = f"# Generated by calliope_model_converter from the legacy {source}.\n"
            dump_yaml(content, dest, header, space_entries=True)
    for rel, df in model.generated_csvs.items():
        dest = out_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(dest, lineterminator="\n")
    if copy_csvs:
        for src, rel in model.csv_copies:
            copy_csv(src, out_dir / rel, model.time_span, model.node_renames)
    for spec in model.derived_csvs:
        write_derived(spec, out_dir, diag, model.node_renames)
